#!/usr/bin/env python3
"""Regenerate src/parse_tables.inc using the Bison supplied by macOS CLT."""
from pathlib import Path
import re
import subprocess
import tempfile

# The right hand action uses one-based child positions in the production.
# A digit passes a node through; '+' adds a child to the existing sequence.
# Function parameters, call arguments and list literals share the list node.
PRECEDENCE = """
%token ASSIGN PRINT ARROW NUMBER ID INPUT
%nonassoc ID
%right ASSIGN
%nonassoc LIST_END
%left APPEND
%nonassoc '@'
%right '?' ':'
%left '|'
%left '&'
%right '!'
%left '=' GT LT GE LE NE
%left '+' '-'
%left '*' '/'
%right UMINUS
%left '.'
%left '[' ']'
%left '(' ')'
%left ABS
"""

RULES = """
program : sequence                          => 1
sequence :                                  => SEQ
sequence : sequence stmt                    => + 1 2
block : '{' sequence '}'                    => BLK 2
stmt : ';'                                  => SEQ
stmt : expr ';'                             => EXP 1
stmt : PRINT expr ';'                       => PRINT 2
stmt : block                                => 1
stmt : '(' expr ')' '?' stmt ':' stmt       => IF 2 5 7
stmt : '(' expr ')' '?' stmt                => IF 2 5 SEQ
stmt : '(' expr ')' '@' stmt                => WHL 2 5
stmt : '(' stmt expr ';' stmt ')' '@' stmt  => FOR 2 3 5 8
stmt : '(' ID ':' expr ')' '@' stmt         => RNG 2 4 7
stmt : ARROW expr ';'                       => RET 2
items : expr %prec LIST_END                 => LST 1
items : items ',' expr %prec LIST_END       => + 1 3
args : %prec LIST_END                       => LST
args : items %prec LIST_END                 => 1
target : ID                                 => 1
target : expr '[' expr ']'                  => IND 1 3
target : '.' ID                             => SGET 2
target : expr '.' ID                        => GET 1 3
expr : target ASSIGN expr                   => SET 1 3
expr : expr APPEND expr                     => APP 1 3
expr : expr '+' expr                        => ADD 1 3
expr : expr '-' expr                        => SUB 1 3
expr : expr '*' expr                        => MUL 1 3
expr : expr '/' expr                        => DIV 1 3
expr : expr '=' expr                        => EQ 1 3
expr : expr GT expr                         => GT 1 3
expr : expr LT expr                         => LT 1 3
expr : expr GE expr                         => GE 1 3
expr : expr LE expr                         => LE 1 3
expr : expr NE expr                         => NE 1 3
expr : '|' expr '|' %prec ABS               => ABS 2
expr : expr '|' expr                        => OR 1 3
expr : expr '&' expr                        => AND 1 3
expr : '!' expr                             => NOT 2
expr : '-' expr %prec UMINUS                => NEG 2
expr : '(' expr ')' %prec '('               => 2
expr : NUMBER                               => 1
expr : '[' args ']'                         => 2
expr : target                               => 1
expr : INPUT                                => INP
expr : '(' args ')' ARROW block             => DEF 2 5
expr : '(' expr ')' ARROW block             => DEF list:2 5
expr : expr '(' args ')'                    => CAL 1 3
expr : '#' block                            => CLS 2
"""


def child(spec):
    if spec == "SEQ":
        return "make_node(Op::SEQ)"
    if spec.startswith("list:"):
        return "make_node(Op::LST, " + child(spec[5:]) + ")"
    return f"std::move(rhs[{int(spec) - 1}])"


def reduction(spec):
    op, *children = spec.split()
    if op.isdigit():
        return "return " + child(op) + ";"
    args = [child(x) for x in children]
    if op == "+":
        return "return append(" + ", ".join(args) + ");"
    return "return make_node(" + ", ".join(["Op::" + op] + args) + ");"


def generate():
    productions, actions = [], []
    for line in RULES.strip().splitlines():
        production, action = line.split("=>")
        productions.append(production.rstrip() + " ;")
        actions.append(reduction(action.strip()))
    with tempfile.TemporaryDirectory() as temp:
        path = Path(temp)
        (path / "grammar.y").write_text(PRECEDENCE + "\n%%\n" + "\n".join(productions))
        subprocess.run(["/usr/bin/bison", "-o", "tables.c", "grammar.y"],
                       cwd=temp, check=True)
        tables = (path / "tables.c").read_text()
    out = ["// Generated by tools/generate_parser.py from the EPQ grammar.", ""]
    token_defs = re.search(r"enum yytokentype\s*\{(.*?)\};", tables, re.S).group(1)
    # Bison also emits enum entries for non-input precedence markers.
    out.append("enum TokenCode {" + token_defs + "};")
    for name in ("YYFINAL", "YYLAST", "YYNTOKENS", "YYPACT_NINF", "YYTABLE_NINF"):
        definition = re.search(r"#define\s+" + name + r"\s+(\(?-?\d+\)?)", tables)
        out.append(f"constexpr int {name} = {definition.group(1)};")
    for name in ("yytranslate", "yypact", "yydefact", "yytable", "yycheck",
                 "yypgoto", "yydefgoto", "yyr1", "yyr2"):
        data = re.search(r"\b" + name + r"\[\]\s*=\s*(\{.*?\});", tables, re.S)
        out.append(f"constexpr short {name}[] = {data.group(1)};")
    out.extend(["", "Node reduce(int rule, Node* rhs) {", "    switch (rule) {"])
    for num, action in enumerate(actions, 2):  # Bison rule 1 is $accept.
        out.append(f"    case {num}: {action}")
    out.extend(['    default: throw std::logic_error("unknown grammar production");',
                "    }", "}", ""])
    root = Path(__file__).resolve().parent.parent
    (root / "src" / "parse_tables.inc").write_text("\n".join(out))


if __name__ == "__main__":
    generate()
